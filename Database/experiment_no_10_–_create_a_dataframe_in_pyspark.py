"""PART B – IMPORT LIBRARIES
Step 2: Import Required Libraries
"""

from pyspark.sql import SparkSession
from pyspark.sql.functions import *

"""PART C – CREATE SPARK SESSION
Step 3: Create Spark Session

A Spark Session is the entry point for working with DataFrames in PySpark.
"""

spark = SparkSession.builder \
    .appName("Data Cleaning and Feature Processing") \
    .getOrCreate()

print("Spark Session Created Successfully")

"""PART D – CREATE SAMPLE DATASET

For this experiment, we will use an Employee Dataset.

The dataset contains:

Employee ID
Name
Department
Age
Salary
Experience
City

We deliberately include missing values, duplicate records and inconsistent department names so that students can perform data cleaning.

Step 4: Create Employee Data
"""

data = [
    (101, "Amit", "IT", 25, 45000, 2, "Pune"),
    (102, "Pooja", "HR", 28, 50000, 4, "Mumbai"),
    (103, "Rahul", "it", 30, 60000, 6, "Pune"),
    (104, "Sneha", "Finance", 26, None, 3, "Nashik"),
    (105, "Karan", "IT", None, 55000, 5, "Pune"),
    (106, "Neha", "HR", 29, 52000, 4, "Mumbai"),
    (106, "Neha", "HR", 29, 52000, 4, "Mumbai"),
    (107, "Ravi", "finance", 35, 70000, 10, "Nagpur"),
    (108, "Priya", "IT", 24, 42000, 1, "Pune"),
    (109, "Arjun", "HR", 27, None, 3, "Mumbai")
]

columns = [
    "Employee_ID",
    "Name",
    "Department",
    "Age",
    "Salary",
    "Experience",
    "City"
]

df = spark.createDataFrame(data, columns)

df.show()

"""PART E – UNDERSTAND THE DATASET
Step 5: Display Schema
"""

df.printSchema()

"""Step 6: Display Number of Rows and Columns"""

print("Number of Rows:", df.count())
print("Number of Columns:", len(df.columns))

"""PART F – DATA QUALITY ASSESSMENT
Step 7: Check Missing Values

Use isNull() to identify missing values.
"""

df.select([
    count(when(col(c).isNull(), c)).alias(c)
    for c in df.columns
]).show()

"""PART G – FIND DUPLICATE RECORDS
Step 8: Identify Duplicate Employee IDs
"""

df.groupBy("Employee_ID") \
  .count() \
  .filter(col("count") > 1) \
  .show()

"""PART H – REMOVE DUPLICATES
Step 9: Remove Duplicate Records
"""

df_clean = df.dropDuplicates(["Employee_ID"])

df_clean.show()

print("Rows after removing duplicates:", df_clean.count())

"""PART I – HANDLE MISSING VALUES
Step 10: Find Average Age

Before filling the missing age, calculate the average.
"""

df_clean.select(avg("Age").alias("Average_Age")).show()

"""Step 11: Fill Missing Age

We can replace the missing age with the average age.
"""

avg_age = df_clean.select(avg("Age")).first()[0]

df_clean = df_clean.fillna({
    "Age": int(avg_age)
})

df_clean.show()

"""Step 12: Find Average Salary"""

df_clean.select(avg("Salary").alias("Average_Salary")).show()

"""Step 13: Fill Missing Salary"""

avg_salary = df_clean.select(avg("Salary")).first()[0]

df_clean = df_clean.fillna({
    "Salary": int(avg_salary)
})

df_clean.show()

"""PART J – STANDARDIZE INCONSISTENT DATA

Currently, the Department column contains:

IT
it
Finance
finance
HR

We want consistent values:

IT
Finance
HR

Step 14: Standardize Department Names
"""

df_clean = df_clean.withColumn(
    "Department",
    initcap(lower(col("Department")))
)

df_clean.show()

df_clean = df_clean.withColumn(
    "Department",
    when(lower(col("Department")) == "it", "IT")
    .when(lower(col("Department")) == "hr", "HR")
    .when(lower(col("Department")) == "finance", "Finance")
    .otherwise(col("Department"))
)

df_clean.show()

"""PART K – FEATURE PROCESSING

Now we create new features from existing data.

Step 15: Create Annual Salary Feature

Suppose the existing salary is monthly salary.

We can calculate annual salary:
"""

df_clean = df_clean.withColumn(
    "Annual_Salary",
    col("Salary") * 12
)

df_clean.show()

"""PART L – CREATE EXPERIENCE CATEGORY
Step 16: Create Experience Level

We can classify employees according to experience.
"""

df_clean = df_clean.withColumn(
    "Experience_Level",
    when(col("Experience") <= 2, "Fresher")
    .when(col("Experience") <= 5, "Intermediate")
    .otherwise("Experienced")
)

df_clean.show()

"""PART M – CREATE AGE GROUP
Step 17: Create Age Group
"""

df_clean = df_clean.withColumn(
    "Age_Group",
    when(col("Age") < 25, "Young")
    .when(col("Age") <= 30, "Adult")
    .otherwise("Senior")
)

df_clean.show()

"""PART N – SELECT REQUIRED FEATURES
Step 18: Display Selected Features
"""

df_clean.select(
    "Employee_ID",
    "Name",
    "Department",
    "Age",
    "Salary",
    "Experience",
    "Annual_Salary",
    "Experience_Level",
    "Age_Group"
).show()

"""PART O – FILTER DATA
Step 19: Find IT Employees
"""

df_clean.filter(
    col("Department") == "IT"
).show()

"""Step 20: Find Employees with Salary Greater Than 50,000"""

df_clean.filter(
    col("Salary") > 50000
).show()

"""PART P – SORT THE DATA
Step 21: Sort Employees by Salary
"""

df_clean.orderBy(
    col("Salary").desc()
).show()

"""PART Q – FEATURE AGGREGATION
Step 22: Average Salary by Department
"""

df_clean.groupBy("Department").agg(
    avg("Salary").alias("Average_Salary"),
    max("Salary").alias("Maximum_Salary"),
    min("Salary").alias("Minimum_Salary")
).show()

"""PART R – FINAL DATASET
Step 23: Display Final Cleaned Dataset
"""

df_clean.show(truncate=False)

"""PART S – CHECK DATA QUALITY AGAIN
Step 24: Verify Missing Values
"""

df_clean.select([
    count(when(col(c).isNull(), c)).alias(c)
    for c in df_clean.columns
]).show()

"""Step 25: Verify Number of Records"""

print("Final Number of Records:", df_clean.count())

"""PART T – SAVE THE PROCESSED DATA
Step 26: Save as CSV

PySpark normally writes CSV output as a folder containing part files.
"""

output_path = "/content/processed_employee_data"

df_clean.coalesce(1).write \
    .mode("overwrite") \
    .option("header", "true") \
    .csv(output_path)

print("Data saved successfully!")

"""PART U – CHECK THE OUTPUT FILE
Step 27: List Output Files
"""

import os

os.listdir(output_path)

"""PART V – DOWNLOAD CSV FROM COLAB
Step 28: Download the Processed Dataset
"""

import glob
